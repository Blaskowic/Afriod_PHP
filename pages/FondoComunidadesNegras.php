    <!-- ¿Qué es? -->
    <div class="section">
        <h4>📌 ¿Qué es el Fondo de Comunidades Negras?</h4>
        <p>
            Es un <span class="badge-highlight">Fondo Especial de Créditos Condonables</span> creado por el Estado colombiano para brindar apoyo educativo a personas pertenecientes a los pueblos 
            <strong>negros, afrocolombianos, raizales y palenqueros</strong>.
        </p>
        <p>
            Este programa está administrado por <strong>ICETEX</strong> con apoyo del Ministerio del Interior y el Ministerio de Educación Nacional, y busca garantizar el acceso, permanencia y culminación de estudios superiores de calidad.
        </p>
    </div>

    <!-- ¿Qué financia? -->
    <div class="section">
        <h4>💰 ¿Qué financia?</h4>
        <p>El Fondo otorga créditos <strong>100% condonables</strong> que pueden cubrir:</p>
        <ul>
            <li>Gastos de <strong>matrícula</strong> en instituciones de educación superior reconocidas en Colombia.</li>
            <li>Gastos de <strong>sostenimiento</strong> para el estudiante durante el semestre.</li>
            <li>Si la matrícula es menor a tres salarios mínimos legales vigentes, la diferencia se puede usar para sostenimiento.</li>
            <li>Hasta dos giros adicionales para gastos relacionados con la elaboración del <strong>trabajo de grado</strong>, según la institución educativa.</li>
        </ul>
        <p>
            En convocatorias recientes, el Fondo ha otorgado hasta <strong>tres salarios mínimos legales mensuales vigentes</strong> por semestre, ya sea para matrícula o sostenimiento, según las necesidades del beneficiario.
        </p>
    </div>

    <!-- A quién va dirigido -->
    <div class="section">
        <h4>👥 ¿A quién va dirigido?</h4>
        <p>Este Fondo está destinado a:</p>
        <ul>
            <li>Personas colombianas que pertenezcan a los pueblos negros, afrocolombianos, raizales o palenqueros.</li>
            <li>Estudiantes inscritos, admitidos o adelantando estudios de pregrado o posgrado en una IES registrada en el SNIES.</li>
            <li>Personas que no cuentan con recursos suficientes para financiar sus estudios superiores.</li>
        </ul>
    </div>

    <!-- Niveles educativos -->
    <div class="section">
        <h4>🎓 ¿Qué niveles educativos financia?</h4>
        <ul>
            <li><strong>Pregrado</strong>: técnico, tecnológico o universitario en Colombia.</li>
            <li><strong>Posgrado</strong>: especialización, maestría, doctorado o posdoctorado en Colombia.</li>
        </ul>
    </div>

    <!-- Requisitos -->
    <div class="section">
        <h4>📋 Requisitos principales</h4>
        <ul>
            <li>Ser colombiano.</li>
            <li>Pertenecer a la etnia de las comunidades negras (afrocolombianos, raizales o palenqueros).</li>
            <li>No contar con recursos económicos suficientes para financiar los estudios.</li>
            <li>El programa académico debe satisfacer una necesidad de formación para la región o la comunidad.</li>
            <li>Estar inscrito o admitido en una institución de educación superior dentro de la vigencia de la convocatoria.</li>
            <li>Presentar un proyecto o trabajo comunitario/social/académico que será desarrollado durante los estudios.</li>
            <li>No haber sido beneficiario anteriormente, salvo casos excepcionales (p. ej., avanzar de técnico/tecnológico a profesional).</li>
        </ul>
    </div>

    <!-- Condiciones de condonación -->
    <div class="section">
        <h4>📜 Condonación del crédito</h4>
        <p>La condonación total del crédito se otorga al estudiante que:</p>
        <ul>
            <li>Culmina exitosamente sus estudios y obtiene el título.</li>
            <li>Ejecuta satisfactoriamente el proyecto de trabajo comunitario o social presentado durante la inscripción.</li>
        </ul>
        <p>
            Los documentos como la carta de solicitud de condonación, acta de grado y el informe final del trabajo comunitario/social/académico deben presentarse dentro de los plazos establecidos (generalmente hasta dos años después de finalizar los estudios).
        </p>
    </div>

