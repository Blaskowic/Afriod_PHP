                    <span class="badge-info-custom">Matrícula Cero</span>, es una estrategia del Gobierno Nacional que garantiza
                    el <strong>pago total de la matrícula ordinaria neta</strong> a estudiantes de programas de pregrado en
                    <strong>Instituciones de Educación Superior públicas</strong>.
                </p>
