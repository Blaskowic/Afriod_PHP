                    <li>✔ Aplica para programas <strong>técnicos, tecnológicos y universitarios</strong>.</li>
                    <li>✔ Modalidad presencial, virtual o a distancia.</li>
                    <li>✔ Instituciones públicas registradas en el SNIES.</li>
                </ul>

                <div class="alert-custom mt-3">
                    <strong>No cubre:</strong> derechos de inscripción, derechos de grado, cursos intersemestrales,
                    extemporáneos, trámites administrativos ni otros derechos pecuniarios.
                </div>
            </div>

            <!-- REQUISITOS -->
            <div class="section">
                <h4>🧾 Requisitos para acceder</h4>
                <ul>
                    <li>Estar matriculado en un programa de <strong>pregrado</strong>.</li>
                    <li>No tener título profesional universitario.</li>
                    <li>Pertenecer a alguno de los siguientes grupos:</li>
                </ul>
                <ul>
                    <li>Estratos 1, 2 o 3.</li>
                    <li>Grupos A, B o C del SISBÉN IV.</li>
                    <li>Población indígena, afrocolombiana, raizal, palenquera o Rrom.</li>
                    <li>Víctimas del conflicto armado.</li>
                    <li>Personas con discapacidad.</li>
                    <li>Comunidades campesinas.</li>
                    <li>Población privada de la libertad.</li>
                </ul>
            </div>

            <!-- DURACIÓN -->
            <div class="section">
                <h4>⏳ Duración del beneficio</h4>
                <p>
                    El beneficio se otorga por el número de periodos necesarios para culminar el programa académico,
                    según los créditos pendientes registrados en el SNIES.
                </p>
                <ul>
                    <li>✔ Técnicos y tecnológicos: hasta <strong>1 periodo adicional</strong> por rezago.</li>
                    <li>✔ Universitarios: hasta <strong>2 periodos adicionales</strong>.</li>
                    <li>✔ No aplica retroactivamente.</li>
                </ul>
            </div>

            <!-- RENOVACIÓN -->
            <div class="section">
